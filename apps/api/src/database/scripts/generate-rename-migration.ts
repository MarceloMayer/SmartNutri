// Verifica slugs duplicados antes de gerar
function checkDuplicateSlugs(map: Record<number, string>): void {
  const slugToId = new Map<string, number>();
  const duplicates: string[] = [];

  for (const [id, name] of Object.entries(map)) {
    const slug = slugify(name);
    const existingId = slugToId.get(slug);

    if (existingId !== undefined) {
      duplicates.push(`  Slug "${slug}" duplicado: id ${existingId} e id ${id} ("${name}")`);
    } else {
      slugToId.set(slug, Number(id));
    }
  }

  if (duplicates.length > 0) {
    console.error('ERRO: Slugs duplicados detectados:');
    duplicates.forEach((msg) => console.error(msg));
    process.exit(1);
  }
}

function escape(value: string): string {
  return value.replace(/'/g, "''");
}

function generateSql(map: Record<number, string>): string {
  const lines: string[] = [
    '-- Migration: 015_humanize_food_names',
    '-- Renomeia os alimentos da TACO para nomes mais naturais ao cotidiano brasileiro.',
    '-- Gerado por: src/database/scripts/generate-rename-migration.ts',
    '',
    'START TRANSACTION;',
    ''
  ];

  for (const [rawId, name] of Object.entries(map)) {
    const id = Number(rawId);
    const slug = slugify(name);
    const safeName = escape(name);
    const safeSlug = escape(slug);
    lines.push(`UPDATE foods SET name = '${safeName}', slug = '${safeSlug}' WHERE id = ${id};`);
  }

  lines.push('');
  lines.push('COMMIT;');
  lines.push('');

  return lines.join('\n');
}

